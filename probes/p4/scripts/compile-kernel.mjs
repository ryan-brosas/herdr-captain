import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileJs } from 'gdp-wired/machine';
import {
  EVENT_NAMES,
  attemptBudgetRule,
  makeAttemptBudgetLaws,
} from '../rules/attempt-budget.mjs';
import {
  INPUT_FILES,
  PACKAGE_ROOT,
  readPinnedGdpWiredVersion,
  sha256,
  verifyManifest,
} from './verify-manifest.mjs';

export { PACKAGE_ROOT, readPinnedGdpWiredVersion, sha256, verifyManifest };

export function readInstalledGdpWiredVersion(packageRoot = PACKAGE_ROOT) {
  const pkg = JSON.parse(
    readFileSync(resolve(packageRoot, 'node_modules/gdp-wired/package.json'), 'utf8'),
  );
  return pkg.version;
}

function parseCompiledMachine(rawSource) {
  const lines = rawSource.trimEnd().split('\n');
  const initIndex = lines.findIndex((line) => line.startsWith('export function init('));
  if (initIndex < 1) {
    throw new Error('Unexpected compileJs output: missing export function init(');
  }

  const helperMap = new Map();
  for (let i = 1; i < initIndex; i += 1) {
    const line = lines[i];
    const singleFn = /^function (\$\w+)\(.*\}$/.exec(line);
    if (singleFn) {
      helperMap.set(singleFn[1], line);
      continue;
    }
    const multiConst = /^const (\$\w+) = function \w+\(/.exec(line);
    if (multiConst) {
      const endIndex = lines.indexOf('};', i);
      if (endIndex < i || endIndex >= initIndex) {
        throw new Error(`Unexpected multiline helper block for ${multiConst[1]}`);
      }
      helperMap.set(multiConst[1], lines.slice(i, endIndex + 1).join('\n'));
      i = endIndex;
      continue;
    }
    throw new Error(`Unrecognized helper line at line ${i + 1}: ${line}`);
  }

  const forkIndex = lines.findIndex((line) => line.startsWith('export function fork('));
  if (forkIndex < initIndex || lines[forkIndex + 2] !== '}') {
    throw new Error('Unexpected compileJs output: missing expected 3-line export function fork(');
  }

  const bodyLines = [
    lines[0],
    ...lines.slice(initIndex, forkIndex),
    ...lines.slice(forkIndex + 3),
  ];
  const body = bodyLines.join('\n').replace(/^export function /gm, 'function ');

  const forbidden = /\b(?:export|import|process|globalThis|eval)\b|\brequire\(|\bFunction\(/;
  if (forbidden.test(body)) {
    throw new Error('Forbidden host or dynamic-eval reference found in compiled machine body');
  }

  // Keep only helpers transitively referenced by the machine body.
  const usedHelpers = new Set();
  for (let changed = true; changed; ) {
    changed = false;
    const reachableText =
      body +
      [...usedHelpers]
        .map((name) => helperMap.get(name))
        .join('\n');
    for (const name of helperMap.keys()) {
      if (!usedHelpers.has(name) && reachableText.includes(`${name}(`)) {
        usedHelpers.add(name);
        changed = true;
      }
    }
  }

  const emittedHelpers = [];
  const helperBlocks = [];
  for (const [name, text] of helperMap.entries()) {
    if (usedHelpers.has(name)) {
      if (forbidden.test(text)) {
        throw new Error(`Forbidden host or dynamic-eval reference found in helper ${name}`);
      }
      emittedHelpers.push(name);
      helperBlocks.push(text);
    }
  }

  const prunedHelpers = [...helperMap.keys()].filter((name) => !usedHelpers.has(name));
  return { body, emittedHelpers, prunedHelpers, helperBlocks };
}

export function compileAttemptBudget({ packageRoot = PACKAGE_ROOT } = {}) {
  const pinned = readPinnedGdpWiredVersion(packageRoot);
  const installed = readInstalledGdpWiredVersion(packageRoot);
  if (installed !== pinned) {
    throw new Error(`Pinned gdp-wired@${pinned} differs from installed gdp-wired@${installed}`);
  }

  const eventCodes = {};
  for (const eventName of EVENT_NAMES) {
    const encoded = attemptBudgetRule.encodeInput({ event: eventName });
    if (typeof encoded.event !== 'number' || !Number.isSafeInteger(encoded.event)) {
      throw new Error(`Unexpected encoding for event ${eventName}: ${JSON.stringify(encoded)}`);
    }
    eventCodes[eventName] = encoded.event;
  }

  const rawCompileJs = compileJs(attemptBudgetRule.machine);
  const { body, emittedHelpers, prunedHelpers, helperBlocks } = parseCompiledMachine(rawCompileJs);
  const { laws, stepLaws } = makeAttemptBudgetLaws(attemptBudgetRule);

  const banner = [
    `// Generated by probes/p4/scripts/compile-kernel.mjs from rules/attempt-budget.mjs with gdp-wired@${installed}. Do not edit.`,
    `// Runtime helpers (${emittedHelpers.join(', ')}) emitted by gdp-wired@${installed}: MIT License, Copyright (c) 2026 Tom X Nguyen (see probes/p4/THIRD_PARTY_NOTICES.md).`,
  ].join('\n');

  const jsSource = [
    banner,
    helperBlocks.join('\n'),
    '',
    `export const EVENT_CODES = Object.freeze(${JSON.stringify(eventCodes)});`,
    '',
    'export const attemptBudget = /* @__PURE__ */ (() => {',
    body,
    'return { init, step };',
    '})();',
    '',
  ].join('\n');

  const dtsSource = [
    `// Generated by probes/p4/scripts/compile-kernel.mjs from rules/attempt-budget.mjs with gdp-wired@${installed}. Do not edit.`,
    'export declare const EVENT_CODES: Readonly<{',
    ...Object.entries(eventCodes).map(([k, v]) => `  readonly ${k}: ${v};`),
    '}>;',
    '',
    'export type AttemptBudgetEventCode = (typeof EVENT_CODES)[keyof typeof EVENT_CODES];',
    '',
    'export interface AttemptBudgetParams {',
    '  readonly initialTotalAttemptCap: number;',
    '  readonly initialFixRoundCap: number;',
    '}',
    '',
    'export interface AttemptBudgetInput {',
    '  readonly event: AttemptBudgetEventCode;',
    '}',
    '',
    'export interface AttemptBudgetScalars {',
    '  readonly totalAttemptsUsed: number;',
    '  readonly totalAttemptCap: number;',
    '  readonly fixRoundsUsed: number;',
    '  readonly fixRoundCap: number;',
    '  readonly openAttempts: number;',
    '}',
    '',
    'export interface AttemptBudgetState {',
    '  readonly scalars: AttemptBudgetScalars;',
    '  readonly maps: Record<string, Map<number, number>>;',
    '  readonly defaults?: Record<string, number>;',
    '}',
    '',
    'export interface AttemptBudgetMachine {',
    '  init(params: AttemptBudgetParams): AttemptBudgetState;',
    '  step(params: AttemptBudgetParams, state: AttemptBudgetState, input: AttemptBudgetInput): AttemptBudgetState;',
    '}',
    '',
    'export declare const attemptBudget: AttemptBudgetMachine;',
    '',
  ].join('\n');

  const inputs = Object.fromEntries(
    INPUT_FILES.map((rel) => [rel, sha256(readFileSync(resolve(packageRoot, rel)))]),
  );
  const outputs = {
    'generated/attempt-budget.js': sha256(jsSource),
    'generated/attempt-budget.d.ts': sha256(dtsSource),
  };

  const manifest = {
    schemaVersion: 1,
    prover: `gdp-wired@${installed}`,
    rule: attemptBudgetRule.machine.name,
    rawCompileJsSha256: sha256(rawCompileJs),
    emittedHelpers,
    prunedHelpers,
    inputs,
    outputs,
    laws: laws.map((law) => law.name),
    stepLaws: stepLaws.map((law) => law.name),
  };
  const manifestSource = `${JSON.stringify(manifest, null, 2)}\n`;

  return {
    prover: manifest.prover,
    rawCompileJs,
    rawCompileJsSha256: manifest.rawCompileJsSha256,
    emittedHelpers,
    prunedHelpers,
    files: {
      'generated/attempt-budget.js': jsSource,
      'generated/attempt-budget.d.ts': dtsSource,
      'generated/manifest.json': manifestSource,
    },
    manifest,
  };
}

export function writeCompiledArtifacts(targetRoot, compiled) {
  for (const [relPath, content] of Object.entries(compiled.files)) {
    const dest = resolve(targetRoot, relPath);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, content, 'utf8');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args[0] === '--write' && args.length === 1) {
    const compiled = compileAttemptBudget();
    writeCompiledArtifacts(PACKAGE_ROOT, compiled);
    console.log(
      JSON.stringify(
        {
          action: 'write',
          prover: compiled.prover,
          rawCompileJsSha256: compiled.rawCompileJsSha256,
          emittedHelpers: compiled.emittedHelpers,
          prunedHelpers: compiled.prunedHelpers,
          outputs: compiled.manifest.outputs,
        },
        null,
        2,
      ),
    );
  } else if (args[0] === '--emit-dir' && args.length === 2) {
    const outRoot = resolve(args[1]);
    const compiled = compileAttemptBudget();
    writeCompiledArtifacts(outRoot, compiled);
    writeFileSync(resolve(outRoot, 'generated/raw-compilejs.txt'), compiled.rawCompileJs, 'utf8');
    console.log(
      JSON.stringify(
        {
          action: 'emit-dir',
          prover: compiled.prover,
          rawCompileJsSha256: compiled.rawCompileJsSha256,
          emittedHelpers: compiled.emittedHelpers,
          prunedHelpers: compiled.prunedHelpers,
          outputs: compiled.manifest.outputs,
        },
        null,
        2,
      ),
    );
  } else {
    console.error('Usage: node scripts/compile-kernel.mjs --write | --emit-dir <dir>');
    process.exit(2);
  }
}
